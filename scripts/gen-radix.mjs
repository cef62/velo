// Writes src/theme/colors/<scale>.ts from @radix-ui/colors (pinned in package.json), in the Park UI shape of
// neutral.ts (gray-like scales) and red.ts (chromatic scales). Run: node scripts/gen-radix.mjs
// The palette overrides ("custom 9–11", design/palettes/README.md §3) live in src/theme/palettes/park.ts, not here.
import * as radix from '@radix-ui/colors'
import { writeFileSync } from 'node:fs'

const GRAYS = ['slate', 'sand']
const CHROMATIC = ['iris', 'jade', 'orange', 'grass', 'crimson', 'blue', 'teal']

const pair = (l, d) => `{ value: { _light: '${l}', _dark: '${d}' } }`
const ref = (n, l, d = l) => pair(`{colors.${n}.${l}}`, `{colors.${n}.${d}}`)

function file(name, gray) {
  const L = radix[name], D = radix[`${name}Dark`], LA = radix[`${name}A`], DA = radix[`${name}DarkA`]
  const steps = []
  for (let i = 1; i <= 12; i++) steps.push(`  '${i}': ${pair(L[`${name}${i}`], D[`${name}${i}`])},`)
  for (let i = 1; i <= 12; i++) steps.push(`  a${i}: ${pair(LA[`${name}A${i}`], DA[`${name}A${i}`])},`)
  const solid = gray
    ? `    bg: {
      DEFAULT: { value: { _light: '{colors.black}', _dark: '{colors.white}' } },
      hover: ${ref(name, 12)},
    },
    fg: { DEFAULT: { value: { _light: '{colors.white}', _dark: '{colors.black}' } } },`
    : `    bg: {
      DEFAULT: ${ref(name, 9)},
      hover: ${ref(name, 10)},
    },
    fg: { DEFAULT: { value: { _light: 'white', _dark: 'white' } } },`
  const fg = gray ? 12 : 'a11'
  const surface = gray
    ? `    bg: {
      DEFAULT: { value: { _light: '{colors.white}', _dark: '{colors.${name}.1}' } },
      hover: ${ref(name, 2)},
      active: ${ref(name, 3)},
    },
    border: {
      DEFAULT: ${ref(name, 6)},
      hover: ${ref(name, 7)},
    },`
    : `    bg: {
      DEFAULT: ${ref(name, 'a2')},
      active: ${ref(name, 'a3')},
    },
    border: {
      DEFAULT: ${ref(name, 'a6')},
      hover: ${ref(name, 'a7')},
    },`
  return `// Generated by scripts/gen-radix.mjs from @radix-ui/colors (Radix ${name}): do not edit by hand.
import { defineSemanticTokens } from '@pandacss/dev'

export const ${name} = defineSemanticTokens.colors({
${steps.join('\n')}
  solid: {
${solid}
  },
  subtle: {
    bg: {
      DEFAULT: ${ref(name, 'a3')},
      hover: ${ref(name, 'a4')},
      active: ${ref(name, 'a5')},
    },
    fg: { DEFAULT: ${ref(name, fg)} },
  },
  surface: {
${surface}
    fg: { DEFAULT: ${ref(name, fg)} },
  },
  outline: {
    bg: {
      hover: ${ref(name, 'a2')},
      active: ${ref(name, 'a3')},
    },
    border: { DEFAULT: ${ref(name, gray ? 6 : 'a7')} },
    fg: { DEFAULT: ${ref(name, fg)} },
  },
  plain: {
    bg: {
      hover: ${ref(name, 'a3')},
      active: ${ref(name, 'a4')},
    },
    fg: { DEFAULT: ${ref(name, fg)} },
  },
})
`
}

for (const n of [...GRAYS, ...CHROMATIC]) {
  writeFileSync(new URL(`../src/theme/colors/${n}.ts`, import.meta.url), file(n, GRAYS.includes(n)))
  console.log(`src/theme/colors/${n}.ts`)
}
